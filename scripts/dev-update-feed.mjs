#!/usr/bin/env node
// A release feed on this computer, for trying updates without publishing anything (docs/UPDATES.md).
//
//   node scripts/dev-update-feed.mjs [options]
//     --version <x.y.z>        the version on offer (default 99.0.0, so it is always newer)
//     --notes <file>           Markdown for the notes (default: a short stand-in)
//     --size-mb <n>            size of the stand-in installer (default 12)
//     --rate-kb <n>            slow the download to this many KB a second, to watch it (default: not slowed)
//     --installer <file>       serve this file instead of generated bytes (see docs/UPDATES.md before installing one)
//     --port <n>               port on 127.0.0.1 (default: any free one)
//     --no-installer           a release without an installer
//     --bad-checksum           advertise a checksum the file does not have
//
// It prints the address to give Cubex as CUBEX_UPDATE_FEED. Cubex takes that variable only for a loopback address,
// so an installed copy cannot be pointed at another machine with it.

import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { createServer } from 'node:http'
import { pathToFileURL } from 'node:url'

const END_OF_NOTES = '<!-- end of notes -->'

const STAND_IN_NOTES = [
  'A stand-in release served from this computer.',
  '',
  '### New',
  '',
  '- **Updates inside the app.** This text is what the update window shows.',
  '- **A second item**, with `code`, a [link](https://example.com) and **bold** text.',
  '',
  '### Fixed',
  '',
  '- Something that used to be wrong.'
].join('\n')

/** Bytes that are the same every time, so the checksum is known before anything is sent. They are not an installer. */
function standInBytes(size) {
  const bytes = Buffer.allocUnsafe(size)
  let state = 0x2545f491
  for (let index = 0; index < size; index++) {
    state ^= state << 13
    state ^= state >>> 17
    state ^= state << 5
    bytes[index] = state & 0xff
  }
  return bytes
}

/**
 * Starts the feed. Resolves with its address (`/latest` on 127.0.0.1), what it serves, the requests it has seen and a
 * `close` that stops it.
 */
export async function startFeed(options = {}) {
  const version = options.version ?? '99.0.0'
  const name = `Cubex-Setup-${version}.exe`
  const bytes = options.installer ? readFileSync(options.installer) : standInBytes(Math.round((options.sizeMb ?? 12) * 1024 * 1024))
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  const rate = options.rateKb ? Math.max(1, Math.round(options.rateKb)) * 1024 : 0
  const requests = []

  const server = createServer((request, response) => {
    const url = new URL(request.url ?? '/', 'http://127.0.0.1')
    requests.push(`${request.method} ${url.pathname}${request.headers.range ? ` (${request.headers.range})` : ''}`)
    const origin = `http://${request.headers.host}`

    if (url.pathname === '/latest') {
      const body = {
        tag_name: `v${version}`,
        name: `Cubex ${version}`,
        body: `${(options.notes ?? STAND_IN_NOTES).trim()}\n\n${END_OF_NOTES}\n\n## Download\n\nThis table is for the release page, and the app does not show it.`,
        draft: false,
        prerelease: false,
        published_at: new Date().toISOString(),
        html_url: `${origin}/release/v${version}`,
        assets: options.noInstaller
          ? []
          : [{
              name,
              size: bytes.length,
              state: 'uploaded',
              content_type: 'application/octet-stream',
              digest: `sha256:${options.badChecksum ? '0'.repeat(64) : sha256}`,
              browser_download_url: `${origin}/download/${name}`
            }]
      }
      response.writeHead(200, { 'Content-Type': 'application/json' })
      response.end(JSON.stringify(body))
      return
    }

    if (url.pathname === `/download/${name}`) {
      const range = /^bytes=(\d+)-$/.exec(request.headers.range ?? '')
      const start = range ? Math.min(Number(range[1]), bytes.length) : 0
      response.writeHead(range ? 206 : 200, {
        'Content-Type': 'application/octet-stream',
        'Content-Length': bytes.length - start,
        ...(range ? { 'Content-Range': `bytes ${start}-${bytes.length - 1}/${bytes.length}` } : {})
      })
      if (!rate) {
        response.end(bytes.subarray(start))
        return
      }
      // Slowed: a tenth of a second's worth at a time.
      const piece = Math.max(1, Math.round(rate / 10))
      let at = start
      const timer = setInterval(() => {
        if (at >= bytes.length) {
          clearInterval(timer)
          response.end()
          return
        }
        response.write(bytes.subarray(at, at + piece))
        at += piece
      }, 100)
      response.on('close', () => clearInterval(timer))
      return
    }

    if (url.pathname.startsWith('/release/')) {
      response.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' })
      response.end('<!doctype html><title>Stand-in release page</title><p>This page stands in for the release page on GitHub. It was opened by the update window of a copy of Cubex that is looking at a feed on this computer.</p>')
      return
    }

    response.writeHead(404, { 'Content-Type': 'text/plain' })
    response.end('Not found')
  })

  await new Promise((resolve, reject) => {
    server.once('error', reject)
    server.listen(options.port ?? 0, '127.0.0.1', resolve)
  })
  const { port } = server.address()
  return {
    url: `http://127.0.0.1:${port}/latest`,
    version,
    installer: { name, size: bytes.length, sha256 },
    requests,
    close: () => new Promise((resolve) => { server.closeAllConnections?.(); server.close(() => resolve()) })
  }
}

function option(args, name) {
  const index = args.indexOf(name)
  return index >= 0 ? args[index + 1] : undefined
}

async function main(args) {
  if (args.includes('--help') || args.includes('-h')) {
    console.log(readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((line) => line.startsWith('//')).map((line) => line.slice(3)).join('\n'))
    return
  }
  const number = (name) => (option(args, name) === undefined ? undefined : Number(option(args, name)))
  const notesFile = option(args, '--notes')
  const feed = await startFeed({
    version: option(args, '--version'),
    notes: notesFile ? readFileSync(notesFile, 'utf8') : undefined,
    sizeMb: number('--size-mb'),
    rateKb: number('--rate-kb'),
    installer: option(args, '--installer'),
    port: number('--port'),
    noInstaller: args.includes('--no-installer'),
    badChecksum: args.includes('--bad-checksum')
  })
  console.log(`Feed ready at ${feed.url}`)
  console.log(`Offering Cubex ${feed.version}, installer ${feed.installer.name} (${(feed.installer.size / 1024 / 1024).toFixed(1)} MB, SHA-256 ${feed.installer.sha256}).`)
  console.log('')
  console.log('Start Cubex with that address in CUBEX_UPDATE_FEED, in the same window:')
  console.log(`  PowerShell:  $env:CUBEX_UPDATE_FEED = '${feed.url}'; & '.\\release\\win-unpacked\\Cubex.exe'`)
  console.log(`  Git Bash:    CUBEX_UPDATE_FEED=${feed.url} ./release/win-unpacked/Cubex.exe`)
  console.log(`  From source: CUBEX_UPDATE_FEED=${feed.url} npm run dev`)
  console.log('')
  console.log('Every request is listed below. Press Ctrl+C to stop.')
  let shown = 0
  setInterval(() => {
    for (; shown < feed.requests.length; shown++) console.log(`  ${feed.requests[shown]}`)
  }, 250).unref?.()
  process.once('SIGINT', () => { void feed.close().then(() => process.exit(0)) })
  // Keep running until stopped.
  await new Promise(() => undefined)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
